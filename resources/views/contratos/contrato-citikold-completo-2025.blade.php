        <p>Por el presente instrumento, el Cliente se obliga para con el Prestador de Servicios a:</p>
        <p class="indent"><strong>a)</strong> Pagar integra y oportunamente el precio estipulado por los Servicios conforme con lo establecido en el Anexo N 1.</p>
        <p class="indent"><strong>b)</strong> Mantener las condiciones necesarias para que el Prestador de Servicios pueda cumplir con sus obligaciones.</p>
