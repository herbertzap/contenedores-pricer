    <div class="clause">
        <h3>PRIMERO. Antecedentes</h3>
        <p><strong>1.1.</strong> Que el Cliente esta interesado en la contratacion del servicio integral de la plataforma tecnologica denominada "CONTENEDORES PRICER", sistema de gestion de contenedores bajo el regimen de admision temporal ante la Aduana de Chile, incluyendo integracion con el sistema HERMES, para el control y administracion de TATC (Titulo de Admision Temporal de Contenedores) y TSTC (Titulo de Salida Temporal de Contenedores).</p>
        <p><strong>1.2.</strong> Que el Proveedor es una empresa especializada en ingenieria y soluciones tecnologicas para empresas del sector aduanero y logistico.</p>
        <p><strong>1.3.</strong> Que las partes estan interesadas en celebrar un contrato de prestacion de servicios, en virtud del cual el Proveedor otorgue al Cliente el derecho de uso del sistema(s) y entregue soporte y asistencia en el uso de los mismos.</p>
    </div>

    <div class="clause">
        <h3>SEGUNDO. Objeto del Contrato</h3>
        <p><strong>2.1.</strong> Por el presente instrumento, el Cliente le encarga al Prestador de Servicios, quien acepta, la prestacion de los servicios especificados en el Anexo N 1 - Condiciones Particulares de Prestacion de Servicios, en los terminos y condiciones indicados en este instrumento (en adelante el "Servicio").</p>
        <p><strong>2.2.</strong> Las presentes CONDICIONES GENERALES PARA LA PRESTACION DE SERVICIOS en conjunto con el ANEXO N 1 - CONDICIONES PARTICULARES DE PRESTACION DE SERVICIOS y los demas Anexos del presente contrato, forman un documento unico para todos los efectos legales a que haya lugar (en adelante el "Contrato").</p>
    </div>

    <div class="clause">
        <h3>TERCERO. Precio, Facturacion y Forma de Pago</h3>
        <p>Las partes acuerdan que el precio a pagar por el Servicio y las condiciones de pago seran los indicados en el Anexo N 1.</p>
    </div>

    <div class="clause">
        <h3>CUARTO. Impuestos</h3>
        <p>Los impuestos, derechos, cargos e imposiciones que se relacionen, directa o indirectamente, con este Contrato seran de cargo de cada parte, segun corresponda. Los valores y precios expresados en el presente Contrato y sus anexos no incluyen tributos y cargas asociados, tales como el IVA.</p>
    </div>

    <div class="clause">
        <h3>QUINTO. Obligaciones del Prestador de Servicios</h3>
        <p>Por medio del presente instrumento, el Prestador de Servicios se obliga a lo siguiente:</p>
        <p class="indent"><strong>a)</strong> <strong>Servicio.</strong> Prestar el Servicio utilizando el personal idoneo bajo su dependencia y subordinacion que sea necesario y conducente, de acuerdo con las necesidades del Cliente y a lo establecido en el presente Contrato y sus Anexos. Es responsabilidad exclusiva del Prestador de Servicios cumplir de manera integra y oportuna, y durante toda la vigencia del presente Contrato, con los estandares de calidad de servicio del Cliente y con los procedimientos internos del Cliente conforme con los cuales se llevara a cabo la prestacion del Servicio.</p>
        <p class="indent"><strong>b)</strong> Respetar y mantener los precios del Servicio, salvo disposicion en contrario del Contrato o sus anexos.</p>
    </div>

