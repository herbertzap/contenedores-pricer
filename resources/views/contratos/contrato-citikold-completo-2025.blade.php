        <p><strong>12.2.</strong> El termino "Informacion Confidencial" no comprende cualquier informacion que: (i) se encontrare en posesion de la respectiva Parte Receptora o de alguno de sus agentes con anterioridad o al momento de su revelacion por la respectiva Parte Informante, (ii) este a disposicion del publico en general, o posteriormente a la celebracion del presente Contrato se ponga a disposicion del publico en general, salvo en cuanto tal disposicion sea consecuencia de un incumplimiento de lo dispuesto por el presente contrato; (iii) hubiere sido legalmente recibida por la respectiva Parte Receptora de un tercero, sin estar obligada a guardar secreto frente tal tercero y cuya revelacion no haya violado ninguna limitacion o restriccion, (iv) fuere desarrollada independientemente por algun agente de una parte, sin conocimiento de cualquier limitacion de revelacion, de conformidad con el presente contrato y sin referencia alguna a la Informacion Confidencial de una Parte Informante; o (v) haya sido autorizada su revelacion por la respectiva Parte Informante, por escrito.</p>
        <p><strong>12.3.</strong> Las Partes se obligan a mantener en estricta confidencialidad y a no revelar a ningun tercero, la Informacion Confidencial. Esta obligacion comprende tambien, sin que ello importe limitacion, el deber de adoptar todas las medidas razonablemente adecuadas para impedir el acceso por cualquier tercero a la Informacion Confidencial, y el deber de mantener en un ambiente restringido y seguro todo soporte material, tecnologico, digital o magnetico que pudiere contener Informacion Confidencial.</p>
        <p><strong>12.4.</strong> En consecuencia, queda especialmente prohibido a las Partes, sin que ello importe limitacion:</p>
        <p class="indent">i. Distribuir o revelar cualquier parte de la Informacion Confidencial, por cualquier medio;</p>
        <p class="indent">ii. Permitir a cualquier tercero el acceso a todo o parte de la Informacion Confidencial; y</p>
        <p class="indent">iii. Usar la Informacion Confidencial para cualquier proposito diferente del mencionado en el presente Contrato, o acordado por escrito con la respectiva Parte Informante. Sin perjuicio de lo anterior, la Parte Receptora podra transmitir Informacion Confidencial a aquellos de sus agentes que tengan la necesidad de conocer la Informacion Confidencial para la adecuada ejecucion de este Contrato, los que deberan estar informados de su contenido y prestar su consentimiento escrito para obligarse en los terminos del mismo. Las Partes acuerdan que seran responsables por sus agentes con respecto a las obligaciones que les impone el presente Contrato.</p>
        <p><strong>12.5.</strong> Sin perjuicio de lo establecido en los parrafos precedentes, no constituira incumplimiento de este Contrato la revelacion en que incurra una Parte Receptora en cuanto sea necesario que sea conocida por empleados o representantes de sus empresas relacionadas (en la medida que se ajusten expresamente a las obligaciones de confidencialidad aqui establecidas) o sea requerida por alguna autoridad publica competente, o en cuanto se encuentre obligada a revelar la Informacion Confidencial por disposicion legal o regulatoria aplicable.</p>
